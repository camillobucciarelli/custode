import CryptoKit
import Foundation
import Security

/// spec 023 T709 — what the app and the AutoFill extension must agree on to
/// authenticate the passkey registration messages they exchange.
///
/// This one file is compiled into BOTH targets (Runner and
/// CredentialProviderExtension), so the two sides cannot drift apart.
///
/// ## Why messages are authenticated
///
/// The port is a Mach service. App Sandbox keeps other sandboxed apps away
/// from its name, but a process that is not sandboxed can look it up, and can
/// also register the name itself while the app is not running. `CFMessagePort`
/// says nothing about who is on the other end. So neither side trusts the
/// port: every request and every reply carries an HMAC-SHA256 under a secret
/// only the two of them can read.
///
/// ## The secret
///
/// 32 random bytes, generated by the app at every launch and stored in the
/// data protection keychain under the shared keychain access group. Reading an
/// item of that group requires code signed with the group in its
/// `keychain-access-groups` entitlement, which only this team's signature can
/// carry. `kSecUseDataProtectionKeychain` is what makes that true on macOS:
/// without it the access group attribute is not applied at all.
///
/// The item is `WhenUnlockedThisDeviceOnly` and not synchronizable: it never
/// leaves this Mac and is not readable while the Mac is locked.
///
/// ## The canonical MAC input
///
/// A MAC covers an ordered list of text fields, encoded as
///
///     UTF-8("custode-passkey-registration-v1")
///     UInt32 big-endian: number of fields
///     for each field: UInt32 big-endian byte length, then its UTF-8 bytes
///
/// Length prefixes, not separators, so no field content can be mistaken for a
/// boundary. An absent optional value is the empty string, a boolean is "1"
/// or "0". The field lists:
///
///     prepare request: "prepare", rpId, userHandle, excludeCredentialIds...
///     commit request:  "commit", rpId, username, userHandle, replaceExisting, nonce
///     result request:  "result", token
///     any reply:       "reply", mac of the request it answers, state, token,
///                      nonce, status, replaces, credentialId, attestationObject
///
/// The first field names the kind, so a MAC for one kind never verifies as
/// another. A reply is bound to its request through the request's MAC, so an
/// answer cannot be replayed for a different request.
enum PasskeyRegistrationWire {
  /// The Mach service the running app registers and the extension looks up.
  ///
  /// The name must be `<app group identifier>.<unique name>`: that prefix is
  /// what lets two sandboxed members of the group reach each other over Mach
  /// IPC without any further entitlement.
  static let portName = SharedAutofillPaths.appGroupId + ".passkey-registration"

  /// Largest message either side accepts on that port, request or reply.
  static let maxMessageBytes = 16 * 1024

  static let domain = "custode-passkey-registration-v1"
  static let secretByteCount = 32
  static let nonceByteCount = 16
  static let tokenByteCount = 16

  /// Same keychain service as the AutoFill cache key, its own account.
  static let keychainAccount = "passkey-registration-secret"

  // MARK: - Field lists

  static func prepareFields(
    rpId: String,
    userHandle: String,
    excludeCredentialIds: [String]
  ) -> [String] {
    ["prepare", rpId, userHandle] + excludeCredentialIds
  }

  static func commitFields(
    rpId: String,
    username: String,
    userHandle: String,
    replaceExisting: Bool,
    nonce: String
  ) -> [String] {
    ["commit", rpId, username, userHandle, replaceExisting ? "1" : "0", nonce]
  }

  static func resultFields(token: String) -> [String] {
    ["result", token]
  }

  /// The fields of a reply, read from the reply object itself so that both
  /// sides derive them the same way. `replaces` absent is "", not "0".
  static func replyFields(requestMac: String, reply: [String: Any]) -> [String] {
    let replaces: String
    if let value = reply["replaces"] as? Bool {
      replaces = value ? "1" : "0"
    } else {
      replaces = ""
    }
    return [
      "reply",
      requestMac,
      reply["state"] as? String ?? "",
      reply["token"] as? String ?? "",
      reply["nonce"] as? String ?? "",
      reply["status"] as? String ?? "",
      replaces,
      reply["credentialId"] as? String ?? "",
      reply["attestationObject"] as? String ?? "",
    ]
  }

  // MARK: - MAC

  static func canonicalBytes(_ fields: [String]) -> Data {
    var data = Data(domain.utf8)
    appendLength(fields.count, to: &data)
    for field in fields {
      let bytes = Data(field.utf8)
      appendLength(bytes.count, to: &data)
      data.append(bytes)
    }
    return data
  }

  private static func appendLength(_ value: Int, to data: inout Data) {
    let length = UInt32(truncatingIfNeeded: value)
    data.append(UInt8((length >> 24) & 0xff))
    data.append(UInt8((length >> 16) & 0xff))
    data.append(UInt8((length >> 8) & 0xff))
    data.append(UInt8(length & 0xff))
  }

  /// base64url, unpadded.
  static func mac(secret: Data, fields: [String]) -> String {
    let code = HMAC<SHA256>.authenticationCode(
      for: canonicalBytes(fields),
      using: SymmetricKey(data: secret)
    )
    return Data(code).base64URLEncodedString
  }

  /// Constant-time comparison, by CryptoKit.
  static func isValid(mac: String, secret: Data, fields: [String]) -> Bool {
    guard let macBytes = Data(base64URLEncoded: mac),
          macBytes.count == SHA256.byteCount else {
      return false
    }
    return HMAC<SHA256>.isValidAuthenticationCode(
      macBytes,
      authenticating: canonicalBytes(fields),
      using: SymmetricKey(data: secret)
    )
  }

  // MARK: - Randomness

  static func randomBytes(_ count: Int) -> Data? {
    var data = Data(count: count)
    let status = data.withUnsafeMutableBytes { buffer -> OSStatus in
      guard let baseAddress = buffer.baseAddress else { return errSecParam }
      return SecRandomCopyBytes(kSecRandomDefault, buffer.count, baseAddress)
    }
    return status == errSecSuccess ? data : nil
  }

  // MARK: - Shared secret (data protection keychain, shared access group)

  /// Replace the stored secret. Called by the app only, at launch.
  /// Returns the `OSStatus` of the write.
  static func storeSecret(_ secret: Data) -> OSStatus {
    guard var query = secretQuery() else { return errSecMissingEntitlement }
    SecItemDelete(query as CFDictionary)
    query[kSecValueData as String] = secret
    query[kSecAttrAccessible as String] = kSecAttrAccessibleWhenUnlockedThisDeviceOnly
    query[kSecAttrSynchronizable as String] = false
    return SecItemAdd(query as CFDictionary, nil)
  }

  /// The secret the app stored at its last launch, or `nil` when there is
  /// none or it cannot be read.
  static func readSecret() -> Data? {
    guard var query = secretQuery() else { return nil }
    query[kSecReturnData as String] = true
    query[kSecMatchLimit as String] = kSecMatchLimitOne
    var result: CFTypeRef?
    let status = SecItemCopyMatching(query as CFDictionary, &result)
    guard status == errSecSuccess,
          let data = result as? Data,
          data.count == secretByteCount else {
      return nil
    }
    return data
  }

  /// `nil` when this process is not signed with the shared access group: the
  /// secret is then neither written nor read, rather than falling back to a
  /// group that is not shared.
  private static func secretQuery() -> [String: Any]? {
    guard let accessGroup = sharedKeychainAccessGroup() else { return nil }
    return [
      kSecClass as String: kSecClassGenericPassword,
      kSecAttrService as String: SharedAutofillPaths.keychainService,
      kSecAttrAccount as String: keychainAccount,
      kSecAttrAccessGroup as String: accessGroup,
      kSecUseDataProtectionKeychain as String: true,
    ]
  }

  /// The full `<team prefix>.<suffix>` group from this process's own
  /// `keychain-access-groups` entitlement. Same lookup as
  /// `SharedAutofillStore.resolveKeychainAccessGroup`.
  private static func sharedKeychainAccessGroup() -> String? {
    guard let task = SecTaskCreateFromSelf(kCFAllocatorDefault) else { return nil }
    var error: Unmanaged<CFError>?
    let value = SecTaskCopyValueForEntitlement(
      task,
      "keychain-access-groups" as CFString,
      &error
    )
    error?.release()
    guard let value else { return nil }
    let groups = (value as? [Any] ?? []).compactMap { $0 as? String }
    return groups.first { group in
      group == SharedAutofillPaths.keychainAccessGroupSuffix ||
        group.hasSuffix(".\(SharedAutofillPaths.keychainAccessGroupSuffix)")
    }
  }
}
